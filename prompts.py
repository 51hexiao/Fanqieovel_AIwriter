def _fmt_review_issues(issues):
    rows = []
    for it in issues or []:
        if isinstance(it, dict):
            w = it.get("where", "")
            rows.append(f"- 【{it.get('type', '其他')}】{it.get('detail', '')}"
                        + (f"（位置：{w}）" if w else ""))
        else:
            rows.append(f"- {it}")
    return chr(10).join(rows) if rows else "（无）"


def _fmt_qc_issues(issues):
    rows = [f"- {x}" for x in issues or []]
    return chr(10).join(rows) if rows else "（无）"


